import fs from "node:fs";
const read=(f)=>fs.readFileSync(f,"utf8");
const errors=[]; const check=(ok,msg)=>{if(!ok) errors.push(msg)};
const css=read("src/styles.css"), html=read("index.html");
const home=read("src/routes/index.tsx"), contact=read("src/routes/contact.tsx"), sample=read("src/routes/sample-work.tsx"), partner=read("src/routes/partner.tsx"), customer=read("src/routes/customer-login.tsx");
check(/--title-card-bg\s*:\s*(?:#fff(?:fff)?|white)/i.test(css),"White title-card background token is missing.");
check(/\.title-card\s*\{/.test(css),"Title-card CSS is missing.");
check(/outline\s*:\s*2px\s+solid\s+var\(--primary\)/.test(css),"Keyboard focus styling is missing.");
check(/overflow-x\s*:\s*hidden/.test(css),"Horizontal overflow protection is missing.");
check(/\.brand-logo\s*\{/.test(css),"Brand-logo sizing guard is missing.");
check(html.includes("family=DM+Sans")&&html.includes("family=Space+Grotesk"),"Production web fonts are not declared.");
check(html.includes("display=swap"),"Web fonts must use display=swap.");
for(const [name,text,markers] of [
  ["Homepage",home,["solution-row v38-panel","v38-panel overflow-hidden","grid gap-4 md:grid-cols-4","hero-tagline"]],
  ["Sample Work",sample,["title-card min-h","title-card grid"]],
  ["Partner",partner,["partner-mobile-nav","title-card p-7","title-card-step"]],
  ["Contact",contact,["title-card p-7","title-card h-fit"]],
  ["Customer Login",customer,["title-card auth-title-card","mobile-page-nav"]],
]) for(const marker of markers) check(text.includes(marker),`${name} finish marker is missing: ${marker}`);
for(const anchor of ["#why","#become","#services","#pricing","#process"]) check(partner.includes(`href=\"${anchor}\"`),`Partner navigation missing ${anchor}.`);
const publicCopy=[home,contact,sample,partner].join("\n");
for(const pattern of [/lorem ipsum/i,/dummy (?:text|content)/i,/placeholder copy/i,/generated by ai/i,/as an ai/i,/service pricing is being finalised/i,/will be added here when finalised/i,/pricing will have its own clear section/i]) check(!pattern.test(publicCopy),`Unfinished public copy remains: ${pattern}`);
if(errors.length){console.error(errors.map(e=>`ERROR: ${e}`).join("\n"));process.exit(1)}
console.log("V46 UI finality verification passed.");
