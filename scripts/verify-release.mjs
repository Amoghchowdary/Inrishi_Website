import fs from "node:fs";
const errors=[],need=(ok,msg)=>{if(!ok)errors.push(msg)};
const pkg=JSON.parse(fs.readFileSync("package.json","utf8"));
const cfg=fs.readFileSync("public/inrishi-config.js","utf8");
const workflow=fs.readFileSync(".github/workflows/deploy-pages.yml","utf8");
const tree=fs.readFileSync("src/routeTree.gen.ts","utf8");
const api=fs.readFileSync("src/lib/apps-script-api.ts","utf8");
const admin=fs.readFileSync("src/components/admin-workspace.tsx","utf8");
const customer=fs.readFileSync("src/routes/customer-login.tsx","utf8");
const contract=JSON.parse(fs.readFileSync("backend-contract.json","utf8"));
need(pkg.version==="61.0.0","Version mismatch");
need(cfg.includes('SITE_ID: "main"'),"Main site identity missing");
need(cfg.includes("https://script.google.com/macros/s/AKfycbzQ1YMIghWp_p3hy3NxsJraffY_AjLA77JlyfYF7YvkGlylLnV2MiDgJViLjByn9ntq/exec"),"Backend URL missing");
need(workflow.includes("Verify deployed Apps Script V61 backend")&&workflow.includes("verify-backend-health.mjs"),"Live backend health gate missing");
need(workflow.includes("www.inrishi.in"),"Main Pages domain missing");
need(contract.version==="61.0.0"&&contract.transport==="apps-script-form-post","V61 backend action contract missing");
need(api.includes('form.method="POST"')&&api.includes("form.submit()")&&!api.includes("ensureRpcBridge"),"V61 stable form-post transport not locked");
need(admin.includes("Change administrator password"),"Admin password-change control missing");
need(customer.includes("Register with Gmail")&&customer.includes("Forgot Customer ID?")&&customer.includes("Forgot Password?"),"Customer registration/recovery controls missing");
need(fs.existsSync("dist/index.html"),"dist missing");
need(tree.includes("'/admin'")&&!tree.includes("'/partner'"),"Main/Partner route boundary failed");
if(errors.length){console.error(errors.map(x=>`ERROR: ${x}`).join("\n"));process.exit(1)}
console.log("V61 Main final production release gate passed: live backend, stable transport, Admin password change and Gmail-based Customer access are verified.");
