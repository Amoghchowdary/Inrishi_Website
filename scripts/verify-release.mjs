import fs from "node:fs";
const errors=[],need=(ok,msg)=>{if(!ok)errors.push(msg)};
const pkg=JSON.parse(fs.readFileSync("package.json","utf8"));
const cfg=fs.readFileSync("public/inrishi-config.js","utf8");
const workflow=fs.readFileSync(".github/workflows/deploy-pages.yml","utf8");
const tree=fs.readFileSync("src/routeTree.gen.ts","utf8");
const api=fs.readFileSync("src/lib/apps-script-api.ts","utf8");
const admin=fs.readFileSync("src/components/admin-workspace.tsx","utf8");
const contract=JSON.parse(fs.readFileSync("backend-contract.json","utf8"));
need(pkg.version==="59.0.0","Version mismatch");
need(cfg.includes('SITE_ID: "main"'),"Main site identity missing");
need(cfg.includes("https://script.google.com/macros/s/AKfycbzQ1YMIghWp_p3hy3NxsJraffY_AjLA77JlyfYF7YvkGlylLnV2MiDgJViLjByn9ntq/exec"),"Backend URL missing");
need(workflow.includes("Verify deployed Apps Script V59 backend")&&workflow.includes("verify-backend-health.mjs"),"Live backend health gate missing from deploy workflow");
need(workflow.includes("www.inrishi.in"),"Main Pages domain missing");
need(contract.version==="59.0.0"&&contract.transport==="apps-script-rpc-bridge","V59 backend action contract missing");
need(api.includes("ensureRpcBridge")&&!api.includes("form.submit()"),"V59 RPC bridge transport not locked");
need(admin.includes("...(detail===undefined?{}:{detail})"),"Admin exact-optional progress payload guard missing");
need(fs.existsSync("dist/index.html"),"dist missing");
need(tree.includes("'/admin'")&&!tree.includes("'/partner'"),"Main/Partner route boundary failed");
if(errors.length){console.error(errors.map(x=>`ERROR: ${x}`).join("\n"));process.exit(1)}console.log("V59 Main final production release gate passed: live backend, action contract, RPC bridge, strict payloads and dist are verified.");
