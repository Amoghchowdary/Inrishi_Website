import fs from "node:fs";
import path from "node:path";
const errors=[];
if(!fs.existsSync("dist/index.html")) errors.push("dist/index.html missing.");
if(!fs.existsSync("dist/favicon.png")) errors.push("dist/favicon.png missing.");
if(!fs.existsSync("dist/inrishi-config.js")) errors.push("dist/inrishi-config.js missing.");
if(!errors.length){
  const text=[]; const css=[]; const js=[];
  const walk=(d)=>{for(const e of fs.readdirSync(d,{withFileTypes:true})){const p=path.join(d,e.name);if(e.isDirectory())walk(p);else if(/\.(html|js|css|svg|json|txt)$/i.test(e.name)){const t=fs.readFileSync(p,"utf8");text.push(t);if(e.name.endsWith(".css"))css.push(t);if(e.name.endsWith(".js"))js.push(t);}}};
  walk("dist"); const joined=text.join("\n"); const cssJoined=css.join("\n");
  if(/Lovable|lovable/.test(joined))errors.push("Built output contains Lovable content.");
  if(/localhost|Testing credentials|Test OTP|Test login|for testing only/i.test(joined))errors.push("Built output contains local/testing content.");
  if(/lorem ipsum|dummy content|placeholder copy|generated by ai|as an ai/i.test(joined))errors.push("Built output contains unfinished copy.");
  const config=fs.readFileSync("dist/inrishi-config.js","utf8");
  if(!config.includes('APP_VERSION: "52.0.0"'))errors.push("Built runtime config is not V52.");
  const index=fs.readFileSync("dist/index.html","utf8");
  if(!index.includes("favicon.png"))errors.push("Built index does not reference the approved Inrishi logo favicon.");
  if(css.length===0)errors.push("No compiled CSS asset was emitted.");
  if(!/--primary:/.test(cssJoined))errors.push("Compiled CSS is missing the INRISHI primary color token.");
  if(!/\.v38-panel:hover/.test(cssJoined))errors.push("Compiled CSS is missing the transparent-to-white service tile hover rule.");
  if(!/background:#fff(?:fff)?!important|background:#ffffff!important/i.test(cssJoined.replace(/\s+/g,"")))errors.push("Compiled CSS is missing the white hover background state.");
  if(js.length===0)errors.push("No JavaScript bundle was emitted.");
}
if(errors.length){console.error(errors.map(e=>`ERROR: ${e}`).join("\n"));process.exit(1);}console.log("V52 built-output verification passed: HTML, JS, config and compiled INRISHI CSS are present.");
